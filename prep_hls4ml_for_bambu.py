#!/usr/bin/env python3
"""
prep_hls4ml_for_bambu.py -- make an hls4ml (Vivado backend) project compilable by Bambu,
without changing what it computes.

hls4ml's firmware only puts the weight values into the C++ when __SYNTHESIS__ is defined
(otherwise it reads w*.txt files at run time), but the open-source ap_types headers refuse
__SYNTHESIS__ (#error). So instead of defining it, this script:
  1. rewrites weights/*.h to always contain the initialised arrays,
  2. removes the run-time load_weights_from_txt block from myproject.cpp,
  3. adds jet_top.cpp: extern "C" wrapper with plain integer ports (raw fixed-point bits),
  4. writes a Bambu C testbench (jet_tb.c) and expected outputs from hls4ml's own
     bit-accurate emulation, for the first --n-tb jets.

Usage: python3 prep_hls4ml_for_bambu.py output/jet/hls4ml_prj output/jet/bambu_src \
           --emu output/jet/hls4ml_prj_emulation.npz [--n-tb 8]
"""
import argparse, os, re, shutil
import numpy as np

ap = argparse.ArgumentParser()
ap.add_argument('prj'); ap.add_argument('out')
ap.add_argument('--emu', required=True)
ap.add_argument('--n-tb', type=int, default=8)
args = ap.parse_args()

fw_src = os.path.join(args.prj, 'firmware')
fw = os.path.join(args.out, 'firmware')
if os.path.exists(args.out):
    shutil.rmtree(args.out)
shutil.copytree(fw_src, fw, ignore=shutil.ignore_patterns('*.so', '*.o'))

# 1. weights always initialised
wre = re.compile(r'#ifndef __SYNTHESIS__\s*\n[^\n]*;\s*\n#else\s*\n(.*?)\n#endif', re.S)
nw = 0
for f in sorted(os.listdir(os.path.join(fw, 'weights'))):
    if not f.endswith('.h'):
        continue
    p = os.path.join(fw, 'weights', f)
    s, n = wre.subn(lambda m: m.group(1), open(p).read())
    assert n == 1, f"{f}: expected one __SYNTHESIS__ block, found {n}"
    open(p, 'w').write(s); nw += 1
print(f"weights: {nw} headers now always initialised")

# 2. no run-time weight loading
p = os.path.join(fw, 'myproject.cpp')
s = open(p).read()
s, n = re.subn(r'#ifndef __SYNTHESIS__\s*\n\s*static bool loaded_weights.*?#endif\s*\n', '', s, flags=re.S)
assert n == 1, "load_weights block not found in myproject.cpp"
if 'nnet::softmax' in s:
    raise SystemExit("myproject.cpp contains softmax: its lookup tables are filled with floating-point exp() "
                     "at run time, which Bambu would build in hardware. Regenerate with --no-softmax "
                     "(argmax/accuracy is unchanged).")
open(p, 'w').write(s)
print("myproject.cpp: run-time weight loading removed")

# 3. wrapper with integer ports
defs = open(os.path.join(fw, 'defines.h')).read()
sig = re.search(r'void myproject\(\s*input_t (\w+)\[(\d+)\],\s*result_t (\w+)\[(\d+)\]', open(p).read())
n_in, n_out = int(sig.group(2)), int(sig.group(4))
def fx(t):
    m = re.search(r'typedef ap_fixed<(\d+),\s*(-?\d+)[^>]*> ' + t + ';', defs)
    return int(m.group(1)), int(m.group(2))
wi, ii = fx('input_t'); wo, io = fx('result_t')
assert wi <= 16, "wrapper assumes input_t of at most 16 bits"
open(os.path.join(args.out, 'jet_top.cpp'), 'w').write(f'''// generated by prep_hls4ml_for_bambu.py
#include "firmware/myproject.h"
// raw two's-complement bits in/out: input  ap_fixed<{wi},{ii}> in int16,
//                                    output ap_fixed<{wo},{io}> in int64 (sign-extended)
extern "C" void jet_top(const short *in_raw, long long *out_raw) {{
    input_t x[{n_in}];
    result_t y[{n_out}];
    for (int i = 0; i < {n_in}; i++) x[i].range({wi-1}, 0) = (unsigned short)in_raw[i];
    myproject(x, y);
    for (int i = 0; i < {n_out}; i++) {{
        ap_int<{wo}> r;
        r.range({wo-1}, 0) = y[i].range({wo-1}, 0);
        out_raw[i] = r.to_int64();
    }}
}}
''')

# 4. testbench + expected values
emu = np.load(args.emu)
x, out = emu['x'][:args.n_tb], emu['out'][:args.n_tb]
def to_raw(v, w, i):                       # ap_fixed default: truncation (floor), wrap
    r = np.floor(v.astype(np.float64) * 2.0 ** (w - i)).astype(np.int64)
    return ((r + 2 ** (w - 1)) % 2 ** w) - 2 ** (w - 1)
xr, er = to_raw(x, wi, ii), np.round(out.astype(np.float64) * 2.0 ** (wo - io)).astype(np.int64)
rows = ',\n      '.join('{' + ','.join(str(v) for v in r) + '}' for r in xr)
open(os.path.join(args.out, 'jet_tb.c'), 'w').write(f'''// generated by prep_hls4ml_for_bambu.py -- Bambu C testbench
#include <stdio.h>
#ifndef NO_MDPI
#include <mdpi/mdpi_user.h>
#endif
void jet_top(const short *in_raw, long long *out_raw);
static const short X[{len(xr)}][{n_in}] = {{
      {rows}}};
int main() {{
  for (int t = 0; t < {len(xr)}; t++) {{
    short in[{n_in}]; long long out[{n_out}];
    for (int i = 0; i < {n_in}; i++) in[i] = X[t][i];
#ifndef NO_MDPI
    m_param_alloc(0, sizeof(in));
    m_param_alloc(1, sizeof(out));
#endif
    jet_top(in, out);
    printf("JET_OUT %d", t);
    for (int i = 0; i < {n_out}; i++) printf(" %lld", out[i]);
    printf("\\n");
  }}
  return 0;
}}
''')
with open(os.path.join(args.out, 'expected.txt'), 'w') as f:
    for t, r in enumerate(er):
        f.write(f"JET_OUT {t} " + ' '.join(str(v) for v in r) + '\n')
print(f"jet_top.cpp, jet_tb.c, expected.txt ({len(xr)} jets) -> {args.out}")
print(f"input ap_fixed<{wi},{ii}>, output ap_fixed<{wo},{io}>, {n_in} in / {n_out} out")
